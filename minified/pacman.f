DECIMAL

VARIABLE PACMAN-SPEED
15 PACMAN-SPEED !

CREATE PACMAN-OPEN
  HEX
  3C C, 7E C, FC C, F0 C, F0 C, FC C, 7E C, 3C C,
  DECIMAL

CREATE PACMAN-CLOSED
  HEX
  3C C, 7E C, FF C, FF C, FF C, FF C, 7E C, 3C C,
  DECIMAL

: SHIFT-BYTE
  DUP 0< IF
    NEGATE LSHIFT 255 AND
  ELSE
    RSHIFT 255 AND
  THEN ;

: DRAW-PACMAN-SHIFTED
  8 0 DO
    OVER I + C@ OVER SHIFT-BYTE
    DISPLAY-BUFFER I + C!
  LOOP 2DROP ;

: PACMAN-OPEN-AT
  PACMAN-OPEN SWAP DRAW-PACMAN-SHIFTED ;

: PACMAN-CLOSED-AT
  PACMAN-CLOSED SWAP DRAW-PACMAN-SHIFTED ;

: PACMAN-STATIC
  0 PACMAN-OPEN-AT
  60 PACMAN-SPEED @ * REFRESH-N ;

: PACMAN-CHOMP
  BEGIN DUP WHILE
    0 PACMAN-OPEN-AT
    PACMAN-SPEED @ REFRESH-N
    0 PACMAN-CLOSED-AT
    PACMAN-SPEED @ REFRESH-N
    1 -
  REPEAT DROP ;

: PACMAN-WALK
  -8
  BEGIN DUP 9 < WHILE
    DUP 1 AND IF
      DUP PACMAN-CLOSED-AT
    ELSE
      DUP PACMAN-OPEN-AT
    THEN
    PACMAN-SPEED @ REFRESH-N
    1 +
  REPEAT DROP ;

: PACMAN-MOVE
  BEGIN DUP WHILE
    PACMAN-WALK
    1 -
  REPEAT DROP ;

: PACMAN-DEMO
  CR ." 8x8 LED Matrix Pacman Demo"
  CR ." 1. Static Pacman..."
  PACMAN-STATIC
  CR ." 2. Chomping in place..."
  6 PACMAN-CHOMP
  CR ." 3. Moving across screen..."
  3 PACMAN-MOVE
  MATRIX-CLS
  REFRESH
  CR ." Done!" CR ;
