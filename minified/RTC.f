HEX

C0 CONSTANT RTC-PORT

10 CONSTANT MASK-CE
20 CONSTANT MASK-WE
40 CONSTANT MASK-SCLK
80 CONSTANT MASK-DATA-OUT

01 CONSTANT MASK-DATA-IN

VARIABLE RTC-STATE
20 RTC-STATE !

: RTC-OUT
  RTC-STATE @ RTC-PORT PC! ;

: SCLK-HI
  MASK-SCLK RTC-STATE @ OR RTC-STATE ! RTC-OUT ;

: SCLK-LO
  MASK-SCLK INVERT RTC-STATE @ AND RTC-STATE ! RTC-OUT ;

: RTC-START
  10 RTC-STATE ! RTC-OUT ;

: RTC-END
  20 RTC-STATE ! RTC-OUT ;

: SHIFT-OUT
  MASK-WE INVERT RTC-STATE @ AND RTC-STATE !
  8 0 DO
    SCLK-LO
    DUP 1 AND IF
      MASK-DATA-OUT RTC-STATE @ OR
    ELSE
      MASK-DATA-OUT INVERT RTC-STATE @ AND
    THEN
    RTC-STATE ! RTC-OUT
    SCLK-HI
    1 RSHIFT
  LOOP
  DROP ;

: SHIFT-IN
  MASK-WE RTC-STATE @ OR RTC-STATE ! RTC-OUT
  0
  8 0 DO
    1 RSHIFT
    SCLK-LO
    RTC-PORT PC@ MASK-DATA-IN AND IF
      80 OR
    THEN
    SCLK-HI
  LOOP ;

: RTC-READ
  RTC-START
  SHIFT-OUT
  SHIFT-IN
  RTC-END ;

: RTC-WRITE
  RTC-START
  SHIFT-OUT
  SHIFT-OUT
  RTC-END ;

: RTC-UNLOCK
  00 8E RTC-WRITE ;

: RTC-LOCK
  80 8E RTC-WRITE ;

: RTC-C@
  1 LSHIFT C1 + RTC-READ ;

: RTC-C!
  RTC-UNLOCK
  1 LSHIFT C0 + RTC-WRITE
  RTC-LOCK ;

: RTC-RAM.
  BASE @ >R HEX
  CR ." DS1302 NVRAM (31 bytes):"
  1F 0 DO
    I 8 MOD 0= IF CR I . ." : " THEN
    I RTC-C@ .
  LOOP
  CR R> BASE ! ;

: BCD>BIN
  DUP 0F AND SWAP 4 RSHIFT 0A * + ;

: BIN>BCD
  0A /MOD 4 LSHIFT + ;

: RTC-INIT
  RTC-UNLOCK
  81 RTC-READ
  7F AND
  80 RTC-WRITE
  RTC-LOCK
  0 RTC-C@ 1 <> IF
    0 0 RTC-C!
  THEN ;

: RTC-SET-TIME
  RTC-UNLOCK
  BIN>BCD 80 RTC-WRITE
  BIN>BCD 82 RTC-WRITE
  BIN>BCD 84 RTC-WRITE
  RTC-LOCK ;

: RTC-SET-DATE
  RTC-UNLOCK
  BIN>BCD 86 RTC-WRITE
  BIN>BCD 88 RTC-WRITE
  BIN>BCD 8C RTC-WRITE
  RTC-LOCK ;

: .2
  DUP 0A < IF ." 0" THEN . ;

: RTC-TIME@
  RTC-START BF SHIFT-OUT
  SHIFT-IN 7F AND BCD>BIN
  SHIFT-IN 7F AND BCD>BIN
  SHIFT-IN 3F AND BCD>BIN
  5 0 DO SHIFT-IN DROP LOOP
  RTC-END ;

: .TIME
  BASE @ >R DECIMAL
  RTC-TIME@
  CR ." Time (HH MM SS): "
  .2 .2 .2
  R> BASE ! ;

: RTC-DATE@
  RTC-START BF SHIFT-OUT
  3 0 DO SHIFT-IN DROP LOOP
  SHIFT-IN 3F AND BCD>BIN
  SHIFT-IN 1F AND BCD>BIN
  SHIFT-IN DROP
  SHIFT-IN BCD>BIN
  SHIFT-IN DROP
  RTC-END ;

: .DATE
  BASE @ >R DECIMAL
  RTC-DATE@
  CR ." Date (YYYY MM DD): 20"
  .2 .2 .2
  R> BASE ! ;

: DST-ADJ
  85 RTC-READ 3F AND BCD>BIN +
  DUP 18 U< IF
    RTC-UNLOCK BIN>BCD 84 RTC-WRITE RTC-LOCK -1
  ELSE
    DROP CR ." Cannot shift DST across midnight" CR 0
  THEN ;

: DST
  DUP 0 RTC-C@ = IF
    ." DST is already " IF ." ON" ELSE ." OFF" THEN CR EXIT
  THEN
  DUP IF 1 ELSE -1 THEN DST-ADJ IF
    DUP 0 RTC-C!
    ." DST " IF ." activated (+1 hour)" ELSE ." deactivated (-1 hour)" THEN CR
  ELSE
    DROP
  THEN ;

: DST?
  0 RTC-C@ 1 = IF ." DST is ON (+1 hr)" ELSE ." DST is OFF" THEN CR ;

