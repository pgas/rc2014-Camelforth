0 CONSTANT ROW-PORT
2 CONSTANT DATA-PORT

VARIABLE ON-TIME
1 ON-TIME !

CREATE DISPLAY-BUFFER 0 C, 0 C, 0 C, 0 C, 0 C, 0 C, 0 C, 0 C,
CREATE TWOS 1 C, 2 C, 4 C, 8 C, 16 C, 32 C, 64 C, 128 C,
CREATE LTWOS 128 C, 64 C, 32 C, 16 C, 8 C, 4 C, 2 C, 1 C,

: POWER2
  TWOS + C@ ;

: SEND-ROW
  POWER2
  ROW-PORT PC!
  DATA-PORT PC! ;

: SENDDATATOROW
  SEND-ROW ;

: DELAY
  BEGIN DUP WHILE 1 - REPEAT DROP ;

: REFRESH
  8 0 DO
    DISPLAY-BUFFER I + C@
    I SEND-ROW
    ON-TIME @ DELAY
    0 DATA-PORT PC!
  LOOP ;

: REFRESH-N
  BEGIN DUP WHILE
    REFRESH
    1 -
  REPEAT DROP ;

: MATRIX-CLS
  DISPLAY-BUFFER 8 0 FILL ;

: MATRIX-FILL
  DISPLAY-BUFFER 8 255 FILL ;

: MATRIX-INVERT
  8 0 DO
    DISPLAY-BUFFER I + DUP C@ 255 XOR SWAP C!
  LOOP ;

: XY1
  7 SWAP -
  DISPLAY-BUFFER + DUP C@
  ROT
  LTWOS + C@
  OR
  SWAP C! ;

: XY0
  7 SWAP -
  DISPLAY-BUFFER + DUP C@
  ROT
  LTWOS + C@
  255 SWAP -
  AND
  SWAP C! ;

: XY?
  7 SWAP -
  DISPLAY-BUFFER + C@
  SWAP LTWOS + C@
  AND 0<> ;

: XY-TOGGLE
  7 SWAP -
  DISPLAY-BUFFER + DUP C@
  ROT
  LTWOS + C@
  XOR
  SWAP C! ;

: ROW!
  7 SWAP - DISPLAY-BUFFER + C! ;

: ROW@
  7 SWAP - DISPLAY-BUFFER + C@ ;

: PDB
  8 0 DO
    DISPLAY-BUFFER I + C@ .
  LOOP ;

: .MATRIX
  PDB ;
